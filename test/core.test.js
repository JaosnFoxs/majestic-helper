const assert = require('assert');
const Core = require('../app/core');
const uk = `Уголовный Кодекс
Глава 15. Преступления против власти.
15.5 Взяточничество.
ч. 1 (R/F) Получение взятки.
Приоритет розыска: ★★★★★
Наказание: 5 лет лишения свободы.
Глава 17. Преступления против порядка управления.
17.3 (R/F) Оскорбление представителя власти при исполнении им своих должностных обязанностей.
Приоритет розыска: ★★★
Наказание: 3 года лишения свободы либо уголовный штраф в размере от $20,000 до $60,000.
Примечание. Оскорбление есть умышленное унижение чести и достоинства личности.
17.9 (R) Грубое или неоднократное оскорбление человека без его согласия.
Приоритет розыска: ★★
Примечание. Содеянное квалифицируется по статье 17.3 настоящего Кодекса.
Подписано Губернатором штата
Обновлен 12.11.2026`;
const rules = `1.4.1 На усмотрение главного куратора фракций с лидера организации может быть снят один выговор за снятый проморолик.
1.7 Лидер несет ответственность за весь свой состав.
4.3 Восстановления в должности допускаются лишь при условии.`;
const all = Core.buildIndex([
  ...Core.parseDoc(uk, { key: 'u', title: 'Уголовный Кодекс', kind: 'law' }),
  ...Core.parseDoc(rules, { key: 'r', title: 'ПЛФ', short: 'ПЛФ', kind: 'rule' }),
]);
const top = (q) => Core.search(all, q).items.map((r) => r.doc + ' ' + r.num);
assert.deepStrictEqual(top('17.3')[0], 'УК 17.3');
assert.strictEqual(all.find((r) => r.num === '17.3').stars, 3);
assert.strictEqual(all.find((r) => r.num === '17.9').lines.length, 3); // «Подписано/Обновлен» не прилипли
assert.deepStrictEqual(top('ук 17.3')[0], 'УК 17.3');
assert.ok(top('оскорбления власти')[0] === 'УК 17.3');          // словоформы + заголовок важнее
assert.ok(top('лидер выговоры').includes('ПЛФ 1.4.1'));        // как на скрине SinSet
assert.ok(top('kblth dsujdjhs').includes('ПЛФ 1.4.1'));        // неверная раскладка
assert.ok(top('взятка').includes('УК 15.5'));
console.log('ok', top('17.3'), top('оскорбление'));
